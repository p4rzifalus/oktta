/* ----------------------------------------------------------------------------
   6. ОБЪЕКТЫ И ИХ ФОРМЫ СТОЛКНОВЕНИЙ

   Картинки лежат в папке public/objects. Чтобы добавить свою — положите PNG
   туда и допишите блок в список ниже.

   Форма — это то, чем объект бьётся о другие объекты. Её не видно.
   Два варианта:

     shape: { kind: 'circle', r: 0.45 }
        круг; r — радиус в долях ширины картинки (0.5 = ровно половина).
        Можно сдвинуть центр: cx / cy (по умолчанию 0.5, 0.5 — центр картинки).

     shape: { kind: 'polygon', points: [[x, y], ...] }
        многоугольник; координаты в долях размера картинки,
        где [0, 0] — левый верхний угол, [1, 1] — правый нижний.
        Точки перечисляются по контуру. Фигура должна быть выпуклой —
        вмятины внутрь движок всё равно срежет.

   Числа ниже посчитаны по силуэтам ваших PNG, правьте как удобно.
   -------------------------------------------------------------------------- */

export type Shape =
  | { kind: 'circle'; r: number; cx?: number; cy?: number }
  | { kind: 'polygon'; points: [number, number][] }

export type ObjectConfig = {
  /** Имя файла в папке public/objects */
  src: string
  shape: Shape
  /** Свой масштаб, если объект должен быть крупнее/мельче остальных (1 = как все) */
  scale?: number
  /** Индивидуальный вес: 2 — вдвое тяжелее обычного, 0.5 — вдвое легче */
  weight?: number
  /** Своя упругость, если этот объект должен прыгать иначе остальных */
  restitution?: number
}

