/* ----------------------------------------------------------------------------
   1. МИР: невесомость, упругость, трение
   -------------------------------------------------------------------------- */

export const WORLD = {
  /** Сила тяжести. 0 — невесомость, объекты плавают.
   *  Поставьте 1, если захотите, чтобы они снова падали вниз и лежали кучей. */
  gravity: 0,

  /** Упругость при столкновении: 0 — гасят удар, 1 — отскакивают как бильярд. */
  restitution: 0.45,

  /** Трение при скольжении друг о друга. В невесомости держите около нуля,
   *  иначе объекты «слипаются» при касании. */
  friction: 0.02,

  /** Трение покоя. Тоже почти не нужно, пока нет опоры под ногами. */
  frictionStatic: 0.05,

  /** Сопротивление среды. Гасит толчок мышью: 0 — объект летит вечно,
   *  0.05 — быстро успокаивается. */
  frictionAir: 0.008,

  /** Плотность = вес на единицу площади. Влияет на то,
   *  насколько тяжело объект сдвинуть с места. */
  density: 0.0025,
}

